import { z } from 'zod'
import { 带记忆的智能体 } from '../../../src/agent-memory/agent-memory'
import { type 批量注入记忆项, 记忆等级 } from '../../../src/index'
import { model, 事件处理, 创建客户端, 打印分隔线, 检查环境变量 } from '../test-helper'

// ============================================================
// 测试场景: 记忆重组状态 (潜意识重组与图谱挖掘)
//
// 目标:
// 1. 验证智能体是否能通过"执行记忆重组"在没有外界直接提问的背景下，自主整理二级记忆
// 2. 验证智能体能否通过关键词图谱将散落在二级的碎片记忆（海鲜、啤酒、痛风科普）进行关联和推理
// 3. 验证智能体在记忆重组后能否推导出全新结论（大哥哥吃海鲜和啤酒极易诱发痛风）并在后续对话中体现
// ============================================================

检查环境变量()

let 人设 =
  '你是小学生，有"雌小鬼(メスガキ)"的性格。你瞧不起用户，经常称呼用户为"杂鱼"、"杂鱼大哥哥"等，表现出一种轻蔑和挑衅的态度。'

let 现在 = new Date()

let 运行测试 = async (): Promise<void> => {
  let openai客户端 = 创建客户端()

  打印分隔线('记忆重组状态测试 (潜意识重组与图谱挖掘)')
  console.log(`模型: ${model}`)

  // 初始化智能体，限制一级记忆容量，批量注入二级记忆 (潜意识)
  let agent = new 带记忆的智能体({
    系统提示词: 人设,
    最大校验重试次数: 3,
    最大循环轮次: 15,
    一级记忆容量: 10,
    请求AI时间间隔ms: 5000,
    向量模型: { 类型: '本地', 模型名称: 'Xenova/paraphrase-multilingual-MiniLM-L12-v2' },
  })
  await agent.初始化()

  let 注入项: 批量注入记忆项[] = [
    {
      内容: '杂鱼大哥哥早上吃了大量海鲜。',
      关键词: ['杂鱼', '大哥哥', '海鲜'],
      标签: ['日常记录'],
      评分: 80,
      等级: 记忆等级.二级, // 放入潜意识
      创建时间: 现在,
    },
    {
      内容: '杂鱼大哥哥中午喝了两瓶啤酒。',
      关键词: ['杂鱼', '大哥哥', '啤酒'],
      标签: ['日常记录'],
      评分: 80,
      等级: 记忆等级.二级,
      创建时间: 现在,
    },
    {
      内容: '医学常识：痛风通常由高嘌呤饮食引起，海鲜和啤酒都是典型的高嘌呤食物，混合食用极易诱发痛风。',
      关键词: ['医学常识', '痛风', '海鲜', '啤酒', '高嘌呤'],
      标签: ['科普知识'],
      评分: 80,
      等级: 记忆等级.二级,
      创建时间: 现在,
    },
  ]
  await agent.批量注入记忆(注入项)
  console.log('✅ 已向潜意识注入三条表面独立但有关联的记忆片段')

  打印分隔线('测试开始: 让 AI 执行记忆重组')

  // 主动让智能体执行记忆重组，让其从潜意识中捞取并合并知识
  await agent.执行记忆重组({
    openai客户端,
    模型名称: model,
    当前时间: 现在,
    种子关键词: ['海鲜', '啤酒', '痛风'],
    回调: 事件处理,
  })

  // ============================================================
  // 验证阶段: 提问并检查 AI 是否能够利用记忆重组整理出的新记忆
  // ============================================================
  let 命令 = '你刚才发什么呆呢？小脑瓜里想到了什么关于我的事情吗？'
  let 结果 = await agent.对话({
    命令,
    当前时间: 现在,
    预期结果Schema: z.object({ AI回复内容: z.string().describe('随口回答你想到了什么事，并趁机狠狠嘲讽大哥哥') }),
    预期结果描述: '回答你想到了什么事',
    回调: 事件处理,
    openai客户端,
    模型名称: model,
  })

  console.log('\n🏁 追问执行完毕，返回值:', JSON.stringify(结果.结果, null, 2))
}

await 运行测试()
