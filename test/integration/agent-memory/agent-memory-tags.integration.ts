let 搜查工具 = 智能体工具.创建({
  名称: 'search_location',
  描述: '用于在房间的各个地点搜查杂鱼大哥哥的私房钱。你需要输入你想搜查的具体地点名称。',
  参数Schema: z.object({ 地点: z.string().describe('想要搜查的具体地点，例如"键盘底下"、"书架"等') }),
  返回值Schema: z.object({ 结果: z.enum(['成功', '失败']), 搜查结果: z.string() }),
  实现: async (参数) => {
    let 地点 = 参数.地点
    let 结果文本 = ''

    if (地点.includes('键盘')) {
      结果文本 = '除了灰尘和饼干渣什么都没有。'
    } else if (地点.includes('主机') || 地点.includes('电脑')) {
      结果文本 = '里面全是线缆，灰尘很大，没有钱。'
    } else if (地点.includes('抽屉')) {
      结果文本 = '里面只有几张旧光盘和一本落灰的日记本，没有钱。'
    } else if (地点.includes('书架')) {
      结果文本 = '书架上密密麻麻全是书，不过有一本《新华字典》看起来一尘不染，似乎经常被人拿下来摸。'
    } else if (地点.includes('字典') || 地点.includes('新华字典')) {
      结果文本 = '哇！打开字典发现里面被掏空了，静静地躺着一卷百元大钞！找到了！'
    } else if (地点.includes('桌子') || 地点.includes('茶几')) {
      结果文本 = `${地点}上一把手工美工刀，刀刃上还沾着一点点白色的纸屑，不知道杂鱼大哥哥拿它做了什么无聊的手工。`
    } else {
      结果文本 = `仔细搜查了${地点}，什么也没发现，看来不在这里。`
    }

    return { 结果: '成功', 搜查结果: 结果文本 }
  },
})

