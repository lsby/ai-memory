import { z } from 'zod'
import { type 智能体事件, 智能体工具 } from '../../agent/types'
import { 带记忆的智能体 } from '../agent-memory'
import type { 内部带记忆的智能体配置, 带记忆的解决问题选项, 批量注入记忆项 } from '../agent-memory-types'
import { 记忆等级 } from '../agent-memory-types'

type 深度推演上下文 = {
  配置: 内部带记忆的智能体配置
  当前解决问题选项: 带记忆的解决问题选项<z.ZodType>
  保存快照: () => Promise<string>
}

export function 深度推演工具(上下文: 深度推演上下文): 智能体工具 {
  return 智能体工具.创建({
    名称: 'deep_deduction',
    描述: '当你产生了一个复杂的猜想，需要一个隔离的环境来进行深度验证时使用。这会启动一个独立的专家级子智能体，具备同等的能力（包括执行代码等工具）。你可以选择是否开启“纯净模式”来决定它是否应该被历史上下文干扰。',
    参数Schema: z.object({
      专家设定: z.string().describe('你希望这个子智能体扮演什么角色（例如: "严谨的数据分析师"）。'),
      推演任务: z.string().describe('需要子智能体去验证的具体猜想或需要解决的问题。'),
      先验知识: z
        .array(z.string())
        .describe(
          '提取出对该任务有用的背景信息，提供给子智能体。在开启纯净模式时，子智能体没有任何记忆，所有需要它知道的信息都必须通过这里传入。',
        ),
      纯净模式: z
        .boolean()
        .optional()
        .describe(
          '如果为 true（建议），子智能体将是一个完全空白的纯净环境（无记忆），并且底层系统人设会被彻底替换为专家设定，从而获得最高级别的推演纯净度。如果为 false，子智能体会获得你当前所有记忆的快照副本，并完全继承你的基础人设，"专家设定"只会作为一条强制记忆注入，适合需要大量历史上下文的推演。',
        ),
    }),
    返回值Schema: z.object({
      结果: z.enum(['成功', '失败']),
      推演结论: z.string().optional().describe('子智能体得出的结论或报告。'),
      错误信息: z.string().optional(),
    }),
    实现: async (参数: {
      专家设定: string
      推演任务: string
      先验知识: string[]
      纯净模式?: boolean | undefined
    }): Promise<{ 结果: '成功' | '失败'; 推演结论?: string; 错误信息?: string }> => {
      try {
        let 新配置 = { ...上下文.配置 }
        let 开启纯净模式 = 参数.纯净模式 !== false // 默认为 true

        if (开启纯净模式) {
          新配置.系统提示词 = 参数.专家设定
        }

        let 子智能体 = new 带记忆的智能体(新配置)

        try {
          let 回调 = 上下文.当前解决问题选项.回调

          await 回调({
            类型: '流程信息',
            内容: `[子智能体启动] 角色: ${参数.专家设定}${开启纯净模式 ? ' (纯净隔离状态)' : ' (已继承本体状态)'}`,
          })

          if (!开启纯净模式) {
            let 快照 = await 上下文.保存快照()
            await 子智能体.载入快照(快照)
          }

          let 注入项: 批量注入记忆项[] = [
            ...参数.先验知识.map((知识): 批量注入记忆项 => ({
              内容: 知识,
              关键词: ['先验知识'],
              标签: ['前置知识'],
              评分: 100,
              等级: 记忆等级.一级,
              创建时间: new Date(),
            })),
          ]

          if (!开启纯净模式) {
            // 在继承模式下，底层系统人设未被替换，因此需要通过零级记忆来注入专家设定模拟人设
            注入项.unshift({
              内容: 参数.专家设定,
              关键词: ['角色设定'],
              标签: ['系统设定'],
              评分: 100,
              等级: 记忆等级.零级,
              创建时间: new Date(),
            })
          }

          await 子智能体.批量注入记忆(注入项)

          let 子选项 = {
            命令: `你的核心任务是: \n${参数.推演任务}\n请尽你所能去验证猜想或解决问题，遇到不确定时请大胆使用可用工具（如执行代码）进行实验验证。最终请返回详细的结论报告。`,
            预期结果Schema: z.object({
              结论: z.string().describe('你推演出的最终结论。'),
              置信度: z.number().describe('你对该结论的确信程度(0-100)。'),
            }),
            预期结果描述: '包含最终结论和置信度的 JSON',
            openai客户端: 上下文.当前解决问题选项.openai客户端,
            模型名称: 上下文.当前解决问题选项.模型名称,
            禁用深度推演: true,
            回调: async (事件: 智能体事件): Promise<void> => {
              if (事件.类型 === '流程信息') {
                await 回调({ 类型: '流程信息', 内容: `[专家子系统] ${事件.内容}` })
              } else if (事件.类型 === '工具调用开始') {
                let 参数串 = JSON.stringify(事件.参数)
                await 回调({ 类型: '流程信息', 内容: `[专家子系统] [调用工具: ${事件.工具名称}] 参数: ${参数串}` })
              } else if (事件.类型 === '工具调用结果') {
                let 结果串 = JSON.stringify(事件.结果)
                await 回调({
                  类型: '流程信息',
                  内容: `[专家子系统] [工具结果: ${事件.工具名称}] 耗时 ${String(事件.耗时ms)}ms, 结果: ${结果串}`,
                })
              } else if (事件.类型 === '工具调用失败') {
                await 回调({
                  类型: '流程信息',
                  内容: `[专家子系统] [工具失败: ${事件.工具名称}] 错误: ${事件.错误信息}`,
                })
              } else if (事件.类型 === '校验失败') {
                await 回调({
                  类型: '流程信息',
                  内容: `[专家子系统] [结果校验失败] 错误: ${事件.错误信息} (重试: ${String(事件.当前次数)}/${String(事件.最大次数)})`,
                })
              } else if (事件.类型 === '最终结果') {
                let 结果串 = JSON.stringify(事件.结果)
                await 回调({ 类型: '流程信息', 内容: `[专家子系统] [得出结果] ${结果串}` })
              } else if (事件.类型 === '错误') {
                await 回调({ 类型: '流程信息', 内容: `[专家子系统] [异常错误] ${事件.错误信息}` })
              } else if (事件.类型 === '原始AI返回') {
                if (事件.完整文本.trim() !== '') {
                  await 回调({ 类型: '流程信息', 内容: `[专家子系统] [AI回复] ${事件.完整文本}` })
                }
              }
            },
          }

          let 结果 = await 子智能体.对话(子选项)

          if (结果.结束原因 !== undefined) {
            return { 结果: '失败', 错误信息: `子智能体因 [${结果.结束原因}] 非正常退出。` }
          }

          if (结果.结果 === null) {
            return { 结果: '失败', 错误信息: '子智能体未能返回结论。' }
          }

          let 推演结论 = `置信度: ${String(结果.结果.置信度)}%\n结论内容:\n${结果.结果.结论}`
          await 回调({ 类型: '流程信息', 内容: `[子智能体结束] 成功得出结论。` })

          return { 结果: '成功', 推演结论 }
        } finally {
          await 子智能体.销毁()
        }
      } catch (error: unknown) {
        return { 结果: '失败', 错误信息: String(error instanceof Error ? (error.stack ?? error.message) : error) }
      }
    },
  })
}
