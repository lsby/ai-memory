/**
 * 按启用的工具名生成默认记忆提示词。
 * - 没有任何记忆管理工具时, 不写认知进化、经验沉淀、关键词与标签这几段;
 * - 没有回忆延伸时, 不提「主动深挖」那句;
 * - 没有任何动态工具时, 不写动态工具系统; 动态工具的各条说明也按启用的工具取舍。
 * 不可变历史原则始终位于最前面; 其后的操作指南在全部启用时与 0.2.3 版的写死文本逐字一致。
 */
export function 生成默认记忆提示词(启用的工具名: readonly string[]): string {
  let 已启用 = (名称: string): boolean => 启用的工具名.includes(名称)
  let 有记忆管理工具 = 记忆管理工具名.some(已启用)
  let 有动态工具 = 动态工具名.some(已启用)

  let 段落列表: string[] = [
    [开头, 已启用(记忆工具名.回忆延伸) ? 二级记忆介绍_前半 + 二级记忆介绍_后半 : 二级记忆介绍_前半].join('\n'),
  ]
  if (有记忆管理工具) 段落列表.push(认知进化段, 经验沉淀段, 关键词与标签段, 工具管理总结句)
  if (有动态工具) {
    let 维护项列表 = [
      已启用(记忆工具名.查看动态工具代码) ? `\`${记忆工具名.查看动态工具代码}\` 查看源码` : null,
      已启用(记忆工具名.更新动态工具) ? `\`${记忆工具名.更新动态工具}\` 修改代码` : null,
      已启用(记忆工具名.删除动态工具) ? `\`${记忆工具名.删除动态工具}\` 删除工具` : null,
    ].filter((项): 项 is string => 项 !== null)
    let 行列表 = [
      动态工具标题,
      已启用(记忆工具名.创建动态工具) ? 动态工具介绍_可创建 : 动态工具介绍_不可创建,
      自动召回项,
    ]
    if (已启用(记忆工具名.调用动态工具)) 行列表.push(手动调用项)
    if (维护项列表.length > 0) 行列表.push(`${维护管理前缀}${维护项列表.join('、')}。`)
    if (已启用(记忆工具名.创建动态工具) || 已启用(记忆工具名.更新动态工具)) 行列表.push(沙盒项)
    段落列表.push(行列表.join('\n'))
  }
  return `${不可变历史原则提示词}\n\n${段落列表.join('\n\n')}\n`
}

