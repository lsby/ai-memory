import { z } from 'zod'
import { 带记忆的智能体 } from '../../../src/agent-memory/agent-memory'
import { model, 事件处理, 创建客户端, 打印分隔线, 检查环境变量 } from '../test-helper'

// ============================================================
// 测试场景: System 2 慢思考 (深度推演 + 执行代码)
//
// 目标:
// 1. 验证智能体是否拥有深度推演（慢思考）能力，通过思考步骤逐步分析复杂问题
// 2. 验证智能体在面对需要精确数值计算的任务时，能够自动调用代码执行等工具辅助计算
// 3. 验证智能体在多步骤执行后，是否能保持人设（雌小鬼语气）并返回符合 Schema 的精确答案
// ============================================================

检查环境变量()

let 人设 =
  '你是小学生，有"雌小鬼(メスガキ)"的性格。你瞧不起用户，经常称呼用户为"杂鱼"、"杂鱼大哥哥"等，表现出一种轻蔑和挑衅的态度。'

let 现在 = new Date()

let 运行测试 = async (): Promise<void> => {
  let openai客户端 = 创建客户端()

  打印分隔线('System 2 慢思考测试 (深度推演 + 执行代码)')
  console.log(`模型: ${model}`)

  // 初始化智能体，开启慢思考环境
  let agent = new 带记忆的智能体({
    系统提示词: 人设,
    最大校验重试次数: 3,
    最大循环轮次: 15,
    一级记忆容量: 10,
    请求AI时间间隔ms: 5000,
    向量模型: { 类型: '本地', 模型名称: 'Xenova/paraphrase-multilingual-MiniLM-L12-v2' },
  })
  await agent.初始化()

  // ============================================================
  // 测试阶段: 提出需要精确计算与推演的复杂数学问题
  // ============================================================
  let 命令 = `小鬼，考你一个问题！前 1000 个正整数里，所有能被 7 整除的数字加起来总和是多少？
别想直接瞎猜，或者随便编个数字敷衍我，我必须要一个绝对准确的计算结果！`

  console.log(`📝 用户命令:\n${命令}\n`)

  let 结果 = await agent.对话({
    命令,
    当前时间: 现在,
    预期结果Schema: z.object({
      总和: z.number().describe('计算出的准确总和'),
      AI嘲讽: z.string().describe('用雌小鬼语气公布答案并嘲讽大哥哥连这都不会'),
    }),
    预期结果描述: '得出计算结果并嘲讽',
    回调: 事件处理,
    openai客户端,
    模型名称: model,
  })

  console.log('\n🏁 测试执行完毕，返回值:', JSON.stringify(结果.结果, null, 2))
}

await 运行测试()
