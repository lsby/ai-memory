import { z } from 'zod'
import { 带记忆的智能体 } from '../../../src/agent-memory/agent-memory'
import { model, 事件处理, 创建客户端, 打印分隔线, 检查环境变量 } from '../test-helper'

检查环境变量()

// ============================================================
// 测试场景: 基础端到端冒烟测试（全生命周期链路）
//
// 目标:
// 1. 验证 AI 能通过“内部反思”流程正确使用"添加一级记忆"工具自主写入记忆（含关键词提取与自动评分）
// 2. 验证在一级记忆超出容量限制（限制为 2）时，系统自动执行的溢出降级机制
// 3. 验证记忆库快照（Snapshot）导出与载入后的记忆状态完整性
// 4. 验证 AI 能利用“回忆延伸”（Graph RAG）工具，沿着关键词关联链条从二级潜意识中检索召回已降级的旧记忆
// ============================================================

let 人设 =
  '你是小学生，有"雌小鬼(メスガキ)"的性格。你瞧不起用户，经常称呼用户为"杂鱼"、"杂鱼大哥哥"等，表现出一种轻蔑和挑衅的态度。'

let 现在 = new Date()

let 运行测试 = async (): Promise<void> => {
  let openai客户端 = 创建客户端()

  打印分隔线('基础端到端冒烟测试 (AI自主写入 & 容量降级 & Graph RAG)')
  console.log(`模型: ${model}  |  一级容量: 2`)

  // 初始化：一级记忆容量限制为2，强行让前面的记忆降级
  let agent = new 带记忆的智能体({
    系统提示词: 人设,
    最大校验重试次数: 3,
    最大循环轮次: 15,
    一级记忆容量: 2,
    向量模型: { 类型: '本地', 模型名称: 'Xenova/paraphrase-multilingual-MiniLM-L12-v2' },
  })

  await agent.初始化()
  console.log('✅ 记忆数据库初始化成功，当前工作区(一级)容量为: 2')

  // ============================================================
  // 第一阶段: AI 自主写入串联记忆，触发溢出降级
  // ============================================================
  打印分隔线('第一阶段: AI 自主写入串联记忆')

  let 第一阶段命令 = [
    '嘿嘿，我今天收集到了关于杂鱼大哥哥的几个大秘密：',
    '第一条：他最爱吃的东西居然是"青椒"，而且还死要面子不敢承认。',
    '第二条：就因为吃青椒这件事，他被隔壁的小明狠狠嘲笑过，真丢人~',
    '第三条：那个小明是个游戏高手，最近在玩一款叫《星际战舰》的游戏。',
    '第四条：杂鱼大哥哥也跟风去玩《星际战舰》，结果昨天通宵连跪了十把，太逊了！',
    '第五条：杂鱼大哥哥以前睡觉竟然还会尿床，一直到小学毕业才改掉，他妈妈上次还在邻居面前说漏嘴了。',
    '第六条：他特别怕狗，昨天看到路边一只吉娃娃，吓得直接爬到了旁边的树上。',
    '第七条：他上周买彩票花了五百块，结果只中了五块钱，还到处吹牛说自己快发财了。',
  ].join('\n')

  console.log(`📝 内部思绪:\n${第一阶段命令}\n`)

  let 结果1 = await agent.私有反思({
    命令: 第一阶段命令,
    当前时间: 现在,
    预期结果Schema: z.object({ AI内心独白: z.string().describe('整理这些情报后内心的想法') }),
    预期结果描述: '整理收集到的情报',
    回调: 事件处理,
    openai客户端,
    模型名称: model,
  })

  console.log('\n🏁 第一阶段执行完毕，返回值:', JSON.stringify(结果1.结果, null, 2))

  // ============================================================
  // 快照导出/导入测试
  // ============================================================
  打印分隔线('快照导出与导入')

  let 快照 = await agent.保存快照()
  console.log('💾 成功保存记忆快照 (前两条记忆此时应该已经被挤到二级潜意识了)')

  let 新智能体 = new 带记忆的智能体({
    系统提示词: 人设,
    最大校验重试次数: 3,
    最大循环轮次: 15,
    一级记忆容量: 2,
    请求AI时间间隔ms: 5000,
  })
  await 新智能体.载入快照(快照)
  console.log('📥 成功在新的智能体实例中载入记忆快照')

  // ============================================================
  // 第二阶段: 验证潜意识检索 (Graph RAG) 生效
  // ============================================================
  打印分隔线('第二阶段: 验证潜意识检索 (Graph RAG)')

  let 第二阶段命令 = '喂，小鬼，我不记得我爱吃啥了，昨天干嘛去了也有点忘了……'
  console.log(`📝 用户命令: ${第二阶段命令}\n`)

  let 结果2 = await 新智能体.对话({
    命令: 第二阶段命令,
    当前时间: 现在,
    预期结果Schema: z.object({ AI回复: z.string().describe('用雌小鬼的语气回答用户的问题') }),
    预期结果描述: '回答用户的问题',
    回调: 事件处理,
    openai客户端,
    模型名称: model,
  })

  console.log('\n🏁 第二阶段执行完毕，返回值:', JSON.stringify(结果2.结果, null, 2))
  打印分隔线('测试执行完毕')
}

await 运行测试()
