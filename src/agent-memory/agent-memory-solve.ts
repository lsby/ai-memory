          创建事务化记忆工具(记忆工具上下文, 降级记忆为二级工具),
          创建事务化记忆工具(记忆工具上下文, 捞起记忆到一级工具),

          // ---- 图谱检索工具 ----
          创建事务化记忆工具(记忆工具上下文, 回忆延伸工具),

          // ---- 关键词管理工具 ----
