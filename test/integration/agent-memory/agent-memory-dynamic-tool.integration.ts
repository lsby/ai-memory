import { z } from 'zod'
import { 带记忆的智能体 } from '../../../src/agent-memory/agent-memory'
import { model, 事件处理, 创建客户端, 打印分隔线, 检查环境变量 } from '../test-helper'

// ============================================================
// 测试场景: 动态工具系统 (Autonomous Tool System)
//
// 目标:
// 1. 验证 AI 是否能根据需求自动生成代码并创建动态工具 (create_dynamic_tool)
// 2. 验证新对话中，系统能否基于向量相似度自动召回该动态工具
// 3. 验证 AI 是否能直接调用被召回的动态工具进行业务处理 (call_dynamic_tool)
// 4. 验证 AI 是否能读取源码 (view_dynamic_tool_code) 并完成代码升级 (update_dynamic_tool)
// ============================================================

async function 运行测试(): Promise<void> {
  检查环境变量()
  let 客户端 = 创建客户端()

  let 智能体 = new 带记忆的智能体({
    系统提示词:
      '你是一个乐于助人的 AI 助手，善于使用并创造新工具。遇到数学运算时，可以创造相关的专门工具来处理，确保准确无误。',
    工具列表: [], // 初始不包含其他业务工具
    最大循环轮次: 5,
    向量模型: { 类型: '本地' },
    存储: { 模式: '内存' },
    自动检索动态工具数量: 3,
  })

  // 必须初始化
  await 智能体.初始化()

  打印分隔线('第一步：让大模型创造一个专门计算商品折扣的动态工具')
  let 创建结果 = await 智能体.对话({
    命令: '我最近要算很多商品打折后的价格，你能不能帮我创建一个动态工具 `calculate_discount`。它接收 原价(price, number) 和 折扣率(discountRate, number, 例如 0.8表示8折)。返回 折后价(finalPrice, number) 和 节省金额(saved, number)。测试用例请传 100 和 0.8。',
    预期结果Schema: z.object({ 回复: z.string().describe('对用户的回复') }),
    预期结果描述: '工具创建成功后的回复',
    回调: 事件处理,
    openai客户端: 客户端,
    模型名称: model,
    当前时间: new Date(),
  })
  console.log('\n🌟 阶段一完成:', 创建结果.结果?.回复)

  打印分隔线('第二步：发起新对话，测试系统是否能自动召回并使用该工具')
  let 调用结果 = await 智能体.对话({
    命令: '好的，现在帮我算一下：一个原价 4567 块钱的电脑，双十一打 75 折，最后多少钱？能省下多少钱？',
    预期结果Schema: z.object({
      最后价格: z.number().describe('计算出的折后价'),
      省下金额: z.number().describe('计算出的节省金额'),
      计算过程或解释: z.string(),
    }),
    预期结果描述: '给出精确的计算结果',
    回调: 事件处理,
    openai客户端: 客户端,
    模型名称: model,
    当前时间: new Date(),
  })

  console.log('\n🌟 阶段二完成:', 调用结果.结果)

  打印分隔线('第三步：查看工具库，甚至让大模型自行读取代码并更新 (修正bug或加功能)')
  // 我们可以在这里继续对话，要求大模型查看并更新该工具，比如支持“是否满减”之类的功能，来验证查看和更新工具的链路。
  let 升级结果 = await 智能体.对话({
    命令: '我想给刚刚那个计算折扣的工具加个功能：它还能接收一个可选的 满减金额(reduction, number)，在打完折之后再减去满减金额。请你先查看一下 `calculate_discount` 的代码，然后再把它更新一下。测试用例请传 1000, 0.8 和 50。',
    预期结果Schema: z.object({ 操作状态: z.string().describe('说明你都做了哪些操作（如查看、更新）') }),
    预期结果描述: '工具更新成功后的状态汇报',
    回调: 事件处理,
    openai客户端: 客户端,
    模型名称: model,
    当前时间: new Date(),
  })

  console.log('\n🌟 阶段三完成:', 升级结果.结果)

  await 智能体.销毁()
}

await 运行测试()
