/** 将三态向量结果解包为工具层使用的 number[] | null */
function 解包向量结果(
  结果: { 类型: '成功'; 向量: number[] } | { 类型: '无模型' } | { 类型: '失败'; 错误信息: string },
): number[] | null {
  if (结果.类型 === '成功') return 结果.向量
  return null
}

